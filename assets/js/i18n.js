const LANG_KEY = "ms_lang";
let CURRENT_LANG = (() => {
  try {
    const l = localStorage.getItem(LANG_KEY);
    return l && I18N[l] ? l : "vi";
  } catch (e) {
    return "vi";
  }
})();

function t(key, vars) {
  let s = (I18N[CURRENT_LANG] && I18N[CURRENT_LANG][key]);
  if (s == null) s = I18N.vi[key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.split("{" + k + "}").join(vars[k]);
    });
  }
  return s;
}

function catName(id) {
  const c = CATEGORIES.find((x) => x.id === id);
  if (!c) return "";
  return t("cat." + c.id) || c.name;
}

function setLang(lang) {
  if (!I18N[lang] || lang === CURRENT_LANG) return;
  CURRENT_LANG = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch (e) {}
  location.reload();
}

/* Dịch các attribute data-i18n tĩnh trong HTML + placeholder dạng data-i18n-ph */
function applyStaticI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  document.documentElement.lang = CURRENT_LANG === "en" ? "en" : "vi";
}
